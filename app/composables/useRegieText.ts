export function regieSlug(value: string) {
  return value.toLowerCase().normalize('NFKD').replace(/\p{Mark}/gu, '').replace(/œ/g, 'oe')
    .replace(/æ/g, 'ae').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 120).replace(/-$/, '')
}

