  'duplicate-slug': 'duplicateSlug', 'duplicate-sku': 'duplicateSku', conflict: 'conflict', dependencies: 'dependencies',
  'category-parent': 'categoryParent', 'category-hidden': 'categoryWarning', 'slug-confirm': 'slugChange',
  'confirm-hide': 'hideCategoryBody', 'media-size': 'mediaInvalid', 'media-invalid': 'mediaInvalid',
